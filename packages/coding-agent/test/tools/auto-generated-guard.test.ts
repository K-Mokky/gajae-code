import { beforeAll, describe, expect, it } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { resetSettingsForTest, Settings } from "@gajae-code/coding-agent/config/settings";
import { DEFAULT_FUZZY_THRESHOLD, executePatchSingle } from "@gajae-code/coding-agent/edit";
import { writethroughNoop } from "@gajae-code/coding-agent/lsp";
import type { ToolSession } from "@gajae-code/coding-agent/tools";
import { assertEditableFile, assertEditableFileContent } from "@gajae-code/coding-agent/tools/auto-generated-guard";
import { ToolError } from "@gajae-code/coding-agent/tools/tool-errors";
import { WriteTool } from "@gajae-code/coding-agent/tools/write";

let tempDir: string;

beforeAll(async () => {
	resetSettingsForTest();
	tempDir = await fs.mkdtemp(path.join(os.tmpdir(), "auto-gen-guard-"));
	await Settings.init({ inMemory: true, cwd: tempDir });
});

const testSettings = (): Settings => Settings.instance;

describe("assertEditableFileContent", () => {
	it("detects canonical TypeScript generated header", () => {
		const content = "// Code generated by sqlc. DO NOT EDIT.\n\nexport const foo = 1;";
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).toThrow(ToolError);
	});

	it("detects @generated marker", () => {
		const content = "// @generated\n\nexport const foo = 1;";
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).toThrow(ToolError);
	});

	it("detects generated-by marker for Python files", () => {
		const content = "# Generated by buf\n\nvalue = 1";
		expect(() => assertEditableFileContent(content, "test.py", testSettings())).toThrow(ToolError);
	});

	it("detects generated-by marker for SQL files", () => {
		const content = "-- generated by sqlc\n\nselect 1;";
		expect(() => assertEditableFileContent(content, "query.sql", testSettings())).toThrow(ToolError);
	});

	it("detects generated markers in leading block comments", () => {
		const content = "/*\n * Code generated by mockery. DO NOT EDIT.\n */\nexport const foo = 1;";
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).toThrow(ToolError);
	});

	it("detects kysely-codegen generated header", () => {
		const content =
			"/**\n * This file was generated by kysely-codegen.\n * Please do not edit it manually.\n */\n\nexport interface Database {}";
		expect(() => assertEditableFileContent(content, "db.ts", testSettings())).toThrow(ToolError);
	});

	it("does not block broad prose comment markers", () => {
		const content = "// auto generated dont edit bla bla\n// this is a hand-written file note\nexport const foo = 1;";
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).not.toThrow();
	});

	it("does not match generated markers after code starts", () => {
		const content = "export const foo = 1;\n\n// Code generated by sqlc. DO NOT EDIT.";
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).not.toThrow();
	});

	it("uses language-specific comment styles", () => {
		const tsContent = "# Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;";
		expect(() => assertEditableFileContent(tsContent, "test.ts", testSettings())).not.toThrow();

		const pyContent = "// Code generated by sqlc. DO NOT EDIT.\nvalue = 1";
		expect(() => assertEditableFileContent(pyContent, "test.py", testSettings())).not.toThrow();
	});

	it("does not block editing the guard file itself", async () => {
		const guardPath = path.join(import.meta.dir, "../../src/tools/auto-generated-guard.ts");
		const content = await Bun.file(guardPath).text();
		expect(() =>
			assertEditableFileContent(content, "packages/coding-agent/src/tools/auto-generated-guard.ts", testSettings()),
		).not.toThrow();
	});

	it("checks only first 1024 bytes of content", () => {
		const prefix = "A".repeat(1024);
		const content = `${prefix}\n// Code generated by sqlc. DO NOT EDIT.`;
		expect(() => assertEditableFileContent(content, "test.ts", testSettings())).not.toThrow();
	});

	it("detects a Generated by scripts/ header", () => {
		const content =
			"/**\n * Generated by scripts/generate-tool-catalog.ts. Do not edit by hand.\n */\nexport const catalog = {};\n";
		expect(() => assertEditableFileContent(content, "catalog.ts", testSettings())).toThrow(ToolError);
	});

	it("detects an Auto-generated by header that is not a known generator name", () => {
		const content = "// Auto-generated by custom-gen. DO NOT EDIT.\nexport const value = 1;\n";
		expect(() => assertEditableFileContent(content, "out.ts", testSettings())).toThrow(ToolError);
	});

	it("still allows generated-by prose that is not a script stamp or auto-generated-by stamp", () => {
		const author = "// Generated by the author for local notes.\nexport const value = 1;\n";
		expect(() => assertEditableFileContent(author, "notes.ts", testSettings())).not.toThrow();

		const helper = "// auto-generated helper for local notes\nexport const value = 1;\n";
		expect(() => assertEditableFileContent(helper, "notes.ts", testSettings())).not.toThrow();

		const automatic = "// This helper was automatically generated by the build notes.\nexport const value = 1;\n";
		expect(() => assertEditableFileContent(automatic, "notes.ts", testSettings())).not.toThrow();
	});
});

describe("assertEditableFile", () => {
	it("detects content marker from file prefix", async () => {
		const filePath = path.join(tempDir, "service.ts");
		await Bun.write(filePath, "// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;");
		await expect(assertEditableFile(filePath, undefined, testSettings())).rejects.toBeInstanceOf(ToolError);
	});

	it("allows normal files", async () => {
		const filePath = path.join(tempDir, "normal.ts");
		await Bun.write(filePath, "// Regular source file\nexport const foo = 1;");
		await expect(assertEditableFile(filePath, undefined, testSettings())).resolves.toBeUndefined();
	});

	it("handles missing files gracefully", async () => {
		const filePath = path.join(tempDir, "does-not-exist.ts");
		await expect(assertEditableFile(filePath, undefined, testSettings())).resolves.toBeUndefined();
	});

	it("blocks *.generated.ts names even when the file has no header marker", async () => {
		const filePath = path.join(tempDir, "nested", "tool-catalog.generated.ts");
		await fs.mkdir(path.dirname(filePath), { recursive: true });
		await Bun.write(filePath, "export const catalog = {};\n");
		await expect(
			assertEditableFile(filePath, "nested/tool-catalog.generated.ts", testSettings()),
		).rejects.toBeInstanceOf(ToolError);
	});

	it("blocks a normal name when the on-disk header says Generated by scripts/", async () => {
		const filePath = path.join(tempDir, "catalog.ts");
		await Bun.write(
			filePath,
			"/**\n * Generated by scripts/generate-tool-catalog.ts. Do not edit by hand.\n */\nexport const catalog = {};\n",
		);
		await expect(assertEditableFile(filePath, "catalog.ts", testSettings())).rejects.toBeInstanceOf(ToolError);
	});

	it("still allows names that only look similar to *.generated.ts", async () => {
		const allowed = ["my-generated.ts", "notes.generated.md", "widget.generated.tsx", "Widget.Generated.ts"];
		for (const name of allowed) {
			const filePath = path.join(tempDir, name);
			await Bun.write(filePath, "export const value = 1;\n");
			await expect(assertEditableFile(filePath, name, testSettings())).resolves.toBeUndefined();
		}
	});

	it("still allows *.generated.ts when blocking is turned off", async () => {
		const filePath = path.join(tempDir, "opt-out.generated.ts");
		await Bun.write(
			filePath,
			"// Auto-generated by scripts/generate-template.ts - DO NOT EDIT\nexport const value = 1;\n",
		);
		const settingsOff = Settings.isolated({ "edit.blockAutoGenerated": false });
		await expect(assertEditableFile(filePath, "opt-out.generated.ts", settingsOff)).resolves.toBeUndefined();
	});
});

function writeSession(cwd: string): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => path.join(cwd, "session.jsonl"),
		getSessionSpawns: () => "*",
		getArtifactsDir: () => path.join(cwd, "artifacts"),
		allocateOutputArtifact: async () => ({ id: "artifact-1", path: path.join(cwd, "artifact-1.log") }),
		settings: Settings.isolated(),
	};
}

describe("WriteTool auto-generated guard", () => {
	it("refuses to overwrite an existing *.generated.ts file", async () => {
		const filePath = path.join(tempDir, "template.generated.ts");
		const original = 'export const html = "keep";\n';
		await Bun.write(filePath, original);
		const tool = new WriteTool(writeSession(tempDir));
		await expect(
			tool.execute("write-generated-name", { path: filePath, content: 'export const html = "changed";\n' }),
		).rejects.toBeInstanceOf(ToolError);
		expect(await Bun.file(filePath).text()).toBe(original);
	});

	it("refuses to overwrite a file stamped Auto-generated by", async () => {
		const filePath = path.join(tempDir, "template.ts");
		const original = '// Auto-generated by scripts/generate-template.ts - DO NOT EDIT\nexport const html = "keep";\n';
		await Bun.write(filePath, original);
		const tool = new WriteTool(writeSession(tempDir));
		await expect(
			tool.execute("write-generated-header", { path: filePath, content: 'export const html = "changed";\n' }),
		).rejects.toBeInstanceOf(ToolError);
		expect(await Bun.file(filePath).text()).toBe(original);
	});

	it("still overwrites a handwritten file and a similar name", async () => {
		const notesPath = path.join(tempDir, "notes.ts");
		const similarPath = path.join(tempDir, "my-generated.ts");
		await Bun.write(notesPath, "// Generated by the author for local notes.\nexport const value = 1;\n");
		await Bun.write(similarPath, "export const value = 1;\n");
		const tool = new WriteTool(writeSession(tempDir));
		const notesResult = await tool.execute("write-notes", {
			path: notesPath,
			content: "// Generated by the author for local notes.\nexport const value = 2;\n",
		});
		const similarResult = await tool.execute("write-similar", {
			path: similarPath,
			content: "export const value = 2;\n",
		});
		expect(notesResult.content.map(part => (part.type === "text" ? part.text : "")).join("\n")).toContain(
			"Successfully wrote",
		);
		expect(similarResult.content.map(part => (part.type === "text" ? part.text : "")).join("\n")).toContain(
			"Successfully wrote",
		);
		expect(await Bun.file(notesPath).text()).toContain("value = 2");
		expect(await Bun.file(similarPath).text()).toContain("value = 2");
	});

	it("still allows WriteTool to create a missing *.generated.ts file", async () => {
		const filePath = path.join(tempDir, "brand-new.generated.ts");
		const tool = new WriteTool(writeSession(tempDir));
		const result = await tool.execute("write-new-generated", {
			path: filePath,
			content: "export const value = 1;\n",
		});
		expect(result.content.map(part => (part.type === "text" ? part.text : "")).join("\n")).toContain(
			"Successfully wrote",
		);
		expect(await Bun.file(filePath).text()).toContain("value = 1");
	});
});

const noopBeginDeferred = (_targetPath: string) => ({
	onDeferredDiagnostics: () => {},
	signal: new AbortController().signal,
	finalize: () => {},
});

function patchSession(cwd: string): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => null,
		getSessionSpawns: () => "*",
		enableLsp: false,
		settings: Settings.isolated(),
		getArtifactsDir: () => null,
		getPlanModeState: () => undefined,
	} as unknown as ToolSession;
}

describe("patch create and generated names", () => {
	it("refuses to create a missing *.generated.ts file through patch", async () => {
		await expect(
			executePatchSingle({
				session: patchSession(tempDir),
				path: "fresh.generated.ts",
				params: { op: "create", diff: "export const value = 1;\n" },
				allowFuzzy: true,
				fuzzyThreshold: DEFAULT_FUZZY_THRESHOLD,
				writethrough: writethroughNoop,
				beginDeferredDiagnosticsForPath: noopBeginDeferred,
			}),
		).rejects.toBeInstanceOf(ToolError);
		expect(await Bun.file(path.join(tempDir, "fresh.generated.ts")).exists()).toBe(false);
	});

	it("still allows patch create of a handwritten name", async () => {
		await executePatchSingle({
			session: patchSession(tempDir),
			path: "fresh-notes.ts",
			params: { op: "create", diff: "export const value = 1;\n" },
			allowFuzzy: true,
			fuzzyThreshold: DEFAULT_FUZZY_THRESHOLD,
			writethrough: writethroughNoop,
			beginDeferredDiagnosticsForPath: noopBeginDeferred,
		});
		expect(await Bun.file(path.join(tempDir, "fresh-notes.ts")).text()).toContain("value = 1");
	});
});
